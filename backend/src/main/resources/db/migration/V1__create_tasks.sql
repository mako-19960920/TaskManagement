-- V1：タスクのテーブルを作る。
-- Flyway を入れる前のデータベース（Hibernate の ddl-auto: update と data.sql で作っていたもの）と同じ形にする。
-- 前からあるデータベースは「V1 まで済み」として扱う（application.yml の baseline-on-migrate）ので、この SQL は新しいデータベースでだけ流れる。

CREATE TABLE tasks (
	id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- タスクID（自動採番）
	title       varchar(255) NOT NULL,                                -- タイトル
	description text,                                                 -- 説明文
	priority    varchar(10)  NOT NULL DEFAULT 'medium',               -- 優先度（high / medium / low）
	due_date    date,                                                 -- 期限
	status      varchar(20)  NOT NULL DEFAULT 'todo',                 -- 状態（todo / in_progress / done）
	position    integer      NOT NULL DEFAULT 0,                      -- 列の中の表示順（0 から）
	hidden      boolean      NOT NULL DEFAULT false,                  -- 非表示か
	created_at  timestamp(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,      -- 作成日時
	updated_at  timestamp(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,      -- 更新日時

	-- 前のデータベースには、同じ意味の CHECK 制約が重なって付いていた（Hibernate が作った2つと、data.sql が付けた1つ）。
	-- 前と同じ形にするため、ここでは3つとも作り、重なりは V2 で外す
	CONSTRAINT tasks_priority_check CHECK (priority IN ('high', 'medium', 'low')),
	CONSTRAINT tasks_status_check CHECK (status IN ('todo', 'in_progress', 'done')),
	CONSTRAINT tasks_values_check CHECK (
		priority IN ('high', 'medium', 'low')
		AND status IN ('todo', 'in_progress', 'done')
		AND title <> ''
	)
);

-- 状態ごとのタスクの取得と、列の中の並び順でのソートに使う
CREATE INDEX idx_tasks_status ON tasks (status);
CREATE INDEX idx_tasks_status_position ON tasks (status, position);
